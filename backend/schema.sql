-- ---------------------------------------------------------------------
-- 14. 触发器：updated_at 自动维护；留痕表只增不改
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $fn$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END
$fn$ LANGUAGE plpgsql;

DO $trg$
DECLARE t TEXT;
BEGIN
    FOR t IN
        SELECT c.table_name
        FROM information_schema.columns c
        JOIN information_schema.tables tb
          ON tb.table_name = c.table_name AND tb.table_schema = c.table_schema
        WHERE c.table_schema = current_schema()
          AND c.column_name = 'updated_at'
          AND tb.table_type = 'BASE TABLE'
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS %I ON %I', 'trg_' || t || '_updated_at', t);
        EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
                       'trg_' || t || '_updated_at', t);
    END LOOP;
END
$trg$;

-- 审计日志：任何 UPDATE / DELETE 都拒绝
CREATE OR REPLACE FUNCTION forbid_change() RETURNS trigger AS $fn$
BEGIN
    RAISE EXCEPTION '表 % 只允许追加，禁止 %', TG_TABLE_NAME, TG_OP USING ERRCODE = 'P0001';
END
$fn$ LANGUAGE plpgsql;

-- 审核留痕拒绝 UPDATE/DELETE，材料版本拒绝 DELETE；
-- 仅清理演示数据的事务可放行：事务内执行 SET LOCAL app.allow_purge = 'on'
CREATE OR REPLACE FUNCTION guard_purge_only() RETURNS trigger AS $fn$
BEGIN
    IF TG_OP = 'DELETE' AND current_setting('app.allow_purge', true) = 'on' THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION '表 % 的记录需留痕保存，禁止 %', TG_TABLE_NAME, TG_OP USING ERRCODE = 'P0001';
END
$fn$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_audit_logs_append_only ON audit_logs;
CREATE TRIGGER trg_audit_logs_append_only BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION forbid_change();

DROP TRIGGER IF EXISTS trg_review_records_guard ON review_records;
CREATE TRIGGER trg_review_records_guard BEFORE UPDATE OR DELETE ON review_records
    FOR EACH ROW EXECUTE FUNCTION guard_purge_only();

DROP TRIGGER IF EXISTS trg_material_versions_guard ON material_versions;
CREATE TRIGGER trg_material_versions_guard BEFORE DELETE ON material_versions
    FOR EACH ROW EXECUTE FUNCTION guard_purge_only();

-- 已备案提交包只读：FILED 后禁止改状态与删除（演示数据清理事务除外）
CREATE OR REPLACE FUNCTION guard_filed_submission() RETURNS trigger AS $fn$
BEGIN
    IF current_setting('app.allow_purge', true) = 'on' THEN
        IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
        RETURN NEW;
    END IF;
    IF OLD.status = 'FILED' AND (TG_OP = 'DELETE' OR NEW.status IS DISTINCT FROM 'FILED') THEN
        RAISE EXCEPTION '已备案提交包 % 为只读归档', OLD.id USING ERRCODE = 'P0001';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END
$fn$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_submissions_filed_guard ON submissions;
CREATE TRIGGER trg_submissions_filed_guard BEFORE UPDATE OR DELETE ON submissions
    FOR EACH ROW EXECUTE FUNCTION guard_filed_submission();

