    code        SMALLINT PRIMARY KEY CHECK (code BETWEEN 1 AND 5),
    stage_key   TEXT     NOT NULL UNIQUE,
    name        TEXT     NOT NULL,
    sort_order  SMALLINT NOT NULL
);

