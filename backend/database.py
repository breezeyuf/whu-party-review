from __future__ import annotations

from sqlalchemy import create_engine
from sqlalchemy.orm import DeclarativeBase, Session, sessionmaker

from config import DATABASE_URL
from migrations import apply_migrations

engine = create_engine(
    DATABASE_URL,
    pool_pre_ping=True,
    # without it an unreachable host can block startup/requests indefinitely (seen on Windows)
    connect_args={"connect_timeout": 10},
    pool_size=10,
    max_overflow=20,
    future=True,
)
SessionLocal = sessionmaker(bind=engine, autoflush=False, autocommit=False, expire_on_commit=False, class_=Session)


class Base(DeclarativeBase):
    pass


def get_db():
    from services.audit import persist_access_denials

    db = SessionLocal()
    try:
        yield db
        persist_access_denials(db)
        db.commit()
        db.info.pop("access_denials", None)
    except Exception:
        db.rollback()
        if db.info.get("access_denials"):
            persist_access_denials(db)
            db.commit()
            db.info.pop("access_denials", None)
        raise
    finally:
        db.close()


