-- Import credentials are encrypted at rest and cleared after one download.
CREATE TABLE IF NOT EXISTS import_password_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    encrypted_payload TEXT,
    file_name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_import_password_files_expires_at ON import_password_files(expires_at);
