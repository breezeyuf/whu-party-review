-- 选型依据：榜题正文（CUSTOM_REQUIREMENTS.md，最高优先级）"数据库要用PostgreSQL"
-- 脚本幂等：可重复执行（IF NOT EXISTS / ON CONFLICT / CREATE OR REPLACE）
-- 枚举统一用 TEXT + CHECK，JSON 结构用 JSONB，时间用 TIMESTAMPTZ，日期用 DATE
-- =====================================================================

SET client_encoding = 'UTF8';

-- ---------------------------------------------------------------------
-- 0. 字典：发展阶段
-- ---------------------------------------------------------------------
