-- ---------------------------------------------------------------------
-- 1. 组织架构与账号
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS orgs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT REFERENCES orgs(id) ON DELETE RESTRICT,
    org_type    TEXT    NOT NULL CHECK (org_type IN ('SCHOOL', 'COLLEGE', 'BRANCH')),
    name        TEXT    NOT NULL,
    code        TEXT    UNIQUE,
    sort_order  INTEGER NOT NULL DEFAULT 0,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    is_demo     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_orgs_root CHECK ((org_type = 'SCHOOL') = (parent_id IS NULL))
);
CREATE INDEX IF NOT EXISTS ix_orgs_parent ON orgs(parent_id);

CREATE TABLE IF NOT EXISTS users (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username              TEXT    NOT NULL UNIQUE,            -- 工号 / 学号
    password_hash         TEXT    NOT NULL,                   -- bcrypt
    real_name             TEXT    NOT NULL,
    gender                TEXT    CHECK (gender IN ('男', '女')),
    org_id                BIGINT  REFERENCES orgs(id) ON DELETE RESTRICT,  -- 所在组织（学生为所在支部）
    email                 TEXT,
    phone_enc             TEXT,                               -- Fernet 加密
    phone_masked          TEXT,                               -- 138****5678
    is_active             BOOLEAN NOT NULL DEFAULT TRUE,
    must_change_password  BOOLEAN NOT NULL DEFAULT TRUE,
    failed_login_count    INTEGER NOT NULL DEFAULT 0,
    locked_until          TIMESTAMPTZ,
    token_version         INTEGER NOT NULL DEFAULT 0,         -- 改密/停用时 +1，旧 token 全部失效
    last_login_at         TIMESTAMPTZ,
    last_login_ip         TEXT,
    is_demo               BOOLEAN NOT NULL DEFAULT FALSE,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_users_org ON users(org_id);

CREATE TABLE IF NOT EXISTS user_roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role        TEXT   NOT NULL CHECK (role IN ('STUDENT', 'BRANCH_REVIEWER', 'CROSS_REVIEWER',
                                                'COLLEGE_REVIEWER', 'ORG_ADMIN', 'SYS_ADMIN')),
    org_id      BIGINT NOT NULL REFERENCES orgs(id) ON DELETE RESTRICT,   -- 数据范围锚点
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_user_roles UNIQUE (user_id, role, org_id)
);
CREATE INDEX IF NOT EXISTS ix_user_roles_role_org ON user_roles(role, org_id);

CREATE TABLE IF NOT EXISTS revoked_tokens (
    jti         TEXT PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    token_type  TEXT   NOT NULL CHECK (token_type IN ('access', 'refresh')),
    expires_at  TIMESTAMPTZ NOT NULL,
    revoked_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_revoked_tokens_exp ON revoked_tokens(expires_at);

-- ---------------------------------------------------------------------
-- 2. 发展批次与交叉互查配对
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS batches (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              TEXT     NOT NULL UNIQUE,
    year              SMALLINT NOT NULL,
    term              TEXT     NOT NULL DEFAULT 'FULL_YEAR' CHECK (term IN ('SPRING', 'AUTUMN', 'FULL_YEAR')),
    stage_codes       JSONB    NOT NULL DEFAULT '[1,2,3,4,5]',   -- 本批次涉及的阶段
    description       TEXT,
    start_date        DATE     NOT NULL,
    end_date          DATE     NOT NULL,
    self_deadline     DATE,     -- 学生提交截止
    branch_deadline   DATE,     -- 支部初审截止
    cross_deadline    DATE,     -- 交叉互查截止
    college_deadline  DATE,     -- 学院复审截止
    org_deadline      DATE,     -- 组织部备案截止
    status            TEXT     NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'CLOSED')),
    is_demo           BOOLEAN  NOT NULL DEFAULT FALSE,
    created_by        BIGINT   REFERENCES users(id) ON DELETE SET NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_batches_range CHECK (end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS cross_review_pairs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id            BIGINT NOT NULL REFERENCES batches(id) ON DELETE CASCADE,
    college_id          BIGINT NOT NULL REFERENCES orgs(id) ON DELETE RESTRICT,
    target_branch_id    BIGINT NOT NULL REFERENCES orgs(id) ON DELETE RESTRICT,   -- 被互查支部
    reviewer_branch_id  BIGINT NOT NULL REFERENCES orgs(id) ON DELETE RESTRICT,   -- 执行互查支部
    reviewer_user_id    BIGINT REFERENCES users(id) ON DELETE SET NULL,          -- 为空 = 该支部全部互查员
    created_by          BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_cross_pairs UNIQUE (batch_id, target_branch_id),
    CONSTRAINT ck_cross_pairs_not_self CHECK (target_branch_id <> reviewer_branch_id)
);
CREATE INDEX IF NOT EXISTS ix_cross_pairs_reviewer ON cross_review_pairs(reviewer_branch_id, batch_id);

-- ---------------------------------------------------------------------
-- 3. 规则库（标准固化）
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS rule_versions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no       INTEGER NOT NULL UNIQUE,
    change_kind      TEXT    NOT NULL,     -- checklists / material-types / time-nodes / time-rules / check-rules / terms / sensitive-phrases / suggestion-templates / prompt-templates / init
    change_action    TEXT    NOT NULL CHECK (change_action IN ('INIT', 'CREATE', 'UPDATE', 'DELETE', 'IMPORT')),
    change_object_id BIGINT,
    change_summary   TEXT    NOT NULL,
    snapshot         JSONB   NOT NULL,     -- 当时全部规则表的完整快照，报告据此复现
    created_by       BIGINT  REFERENCES users(id) ON DELETE SET NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS material_types (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 TEXT    NOT NULL UNIQUE,        -- APPLICATION_LETTER / THOUGHT_REPORT ...
    name                 TEXT    NOT NULL,
    stage_codes          JSONB   NOT NULL DEFAULT '[]',  -- 所属阶段
    title_keywords       JSONB   NOT NULL DEFAULT '[]',  -- 识别关键词（标题/首段）
    exclude_keywords     JSONB   NOT NULL DEFAULT '[]',
    element_template     JSONB   NOT NULL DEFAULT '[]',  -- 内容要素 [{key,name,keywords,required}]
    format_requirements  JSONB   NOT NULL DEFAULT '{}',  -- 文书要素/签名位/盖章位/必填栏/篇幅/手写
    date_node_map        JSONB   NOT NULL DEFAULT '{}',  -- 落款/字段 → 时间节点映射
    description          TEXT,
    is_active            BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order           INTEGER NOT NULL DEFAULT 0,
    updated_by           BIGINT  REFERENCES users(id) ON DELETE SET NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS checklist_items (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_code         SMALLINT NOT NULL REFERENCES stages(code),
    material_type_id   BIGINT   NOT NULL REFERENCES material_types(id) ON DELETE RESTRICT,
    quantity_mode      TEXT     NOT NULL DEFAULT 'FIXED' CHECK (quantity_mode IN ('FIXED', 'PER_PERIOD')),
    fixed_count        INTEGER  NOT NULL DEFAULT 1 CHECK (fixed_count >= 0),
    period_months      INTEGER  CHECK (period_months IS NULL OR period_months > 0),
    period_start_node  TEXT,    -- 如 T04
    period_end_node    TEXT,    -- 如 T08；缺失时取批次截止日/当前日期
    is_required        BOOLEAN  NOT NULL DEFAULT TRUE,
    requirement_text   TEXT,
    sort_order         INTEGER  NOT NULL DEFAULT 0,
    is_active          BOOLEAN  NOT NULL DEFAULT TRUE,
    updated_by         BIGINT   REFERENCES users(id) ON DELETE SET NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_checklist UNIQUE (stage_code, material_type_id),
    CONSTRAINT ck_checklist_period CHECK (quantity_mode = 'FIXED' OR (period_months IS NOT NULL AND period_start_node IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS time_node_defs (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                  TEXT     NOT NULL UNIQUE,      -- T01..T21，派生节点 D01
    name                  TEXT     NOT NULL,
    value_kind            TEXT     NOT NULL CHECK (value_kind IN ('DATE', 'DATE_RANGE', 'DATE_SEQ', 'DERIVED')),
    has_hours             BOOLEAN  NOT NULL DEFAULT FALSE,   -- T10 集中培训学时
    stage_code            SMALLINT REFERENCES stages(code),  -- 节点产生的阶段
    required_from_stage   SMALLINT REFERENCES stages(code),  -- 从该阶段提交包起必须具备
    source_material_codes JSONB    NOT NULL DEFAULT '[]',
    extract_keywords      JSONB    NOT NULL DEFAULT '[]',    -- 正文抽取上下文关键词
    derive_expr           JSONB,                             -- {"base":"T14","offset":{"value":1,"unit":"YEAR"}}
    sort_order            INTEGER  NOT NULL DEFAULT 0,
    is_active             BOOLEAN  NOT NULL DEFAULT TRUE,
    updated_by            BIGINT   REFERENCES users(id) ON DELETE SET NULL,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_node_derived CHECK ((value_kind = 'DERIVED') = (derive_expr IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS suggestion_templates (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           TEXT    NOT NULL UNIQUE,
    rule_code      TEXT,                     -- 对应规则编码，可为空（通用模板）
    title          TEXT    NOT NULL,
    template_text  TEXT    NOT NULL,         -- 支持 {材料名}{节点名}{实际值}{要求值}{页码}{原文}{标准写法}
    example_text   TEXT,
    is_active      BOOLEAN NOT NULL DEFAULT TRUE,
    updated_by     BIGINT  REFERENCES users(id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS time_rules (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                    TEXT    NOT NULL UNIQUE,       -- R-T01..
    name                    TEXT    NOT NULL,
    rule_type               TEXT    NOT NULL CHECK (rule_type IN ('AGE', 'INTERVAL', 'ORDER', 'SEQ_GAP', 'SEQ_COUNT',
                                     'DURATION', 'DERIVED', 'CONSISTENCY', 'VALID_DATE', 'REQUIRED_NODES',
                                     'IN_RANGE', 'COMPOSITE')),             -- 仅用于界面分组，执行逻辑见 params.checks
    params                  JSONB   NOT NULL DEFAULT '{"checks": []}',     -- {"checks":[原子校验...]}，全部通过才算通过
    applies_stages          JSONB   NOT NULL DEFAULT '[]', -- 在哪些阶段的提交包上执行，空 = 全部
    severity                TEXT    NOT NULL CHECK (severity IN ('BLOCK', 'WARN', 'INFO', 'CALC')),
    basis                   TEXT,                          -- 规则依据（条款出处）
    message_template        TEXT    NOT NULL,
    suggestion_template_id  BIGINT  REFERENCES suggestion_templates(id) ON DELETE SET NULL,
    is_active               BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order              INTEGER NOT NULL DEFAULT 0,
    updated_by              BIGINT  REFERENCES users(id) ON DELETE SET NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS check_rules (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                    TEXT    NOT NULL UNIQUE,       -- R-F01.. / R-C01..
    category                TEXT    NOT NULL CHECK (category IN ('FORMAT', 'CONTENT')),
    name                    TEXT    NOT NULL,
    engine                  TEXT    NOT NULL CHECK (engine IN ('RULE', 'LLM', 'RULE_LLM')),
    applies_to              JSONB   NOT NULL DEFAULT '[]', -- 材料类型 code 列表，空 = 全部
    params                  JSONB   NOT NULL DEFAULT '{}',
    severity                TEXT    NOT NULL CHECK (severity IN ('BLOCK', 'WARN', 'INFO')),
    needs_human_judgement   BOOLEAN NOT NULL DEFAULT FALSE,
    basis                   TEXT,
    message_template        TEXT    NOT NULL,
    suggestion_template_id  BIGINT  REFERENCES suggestion_templates(id) ON DELETE SET NULL,
    is_optional             BOOLEAN NOT NULL DEFAULT FALSE,
    is_active               BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order              INTEGER NOT NULL DEFAULT 0,
    updated_by              BIGINT  REFERENCES users(id) ON DELETE SET NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS political_terms (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_type       TEXT    NOT NULL DEFAULT 'VARIANT' CHECK (term_type IN ('VARIANT', 'SEQUENCE')),
    standard_text   TEXT    NOT NULL UNIQUE,
    wrong_variants  JSONB   NOT NULL DEFAULT '[]',   -- VARIANT：常见错误写法
    sequence_items  JSONB   NOT NULL DEFAULT '[]',   -- SEQUENCE：标准并列顺序
    category        TEXT,                            -- 指导思想 / 党的性质 / 会议届次 ...
    severity        TEXT    NOT NULL DEFAULT 'WARN' CHECK (severity IN ('BLOCK', 'WARN', 'INFO')),
    note            TEXT,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    updated_by      BIGINT  REFERENCES users(id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sensitive_phrases (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phrase      TEXT    NOT NULL,
    match_type  TEXT    NOT NULL DEFAULT 'KEYWORD' CHECK (match_type IN ('KEYWORD', 'REGEX')),
    category    TEXT    NOT NULL CHECK (category IN ('IDEOLOGY', 'MOTIVATION', 'OTHER')),
    risk_level  TEXT    NOT NULL DEFAULT 'MEDIUM' CHECK (risk_level IN ('HIGH', 'MEDIUM', 'LOW')),
    risk_note   TEXT,
    suggestion  TEXT,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    updated_by  BIGINT  REFERENCES users(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_sensitive UNIQUE (phrase, category)
);

CREATE TABLE IF NOT EXISTS prompt_templates (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           TEXT    NOT NULL UNIQUE,   -- CLASSIFY / EXTRACT / CONTENT_CHECK / SUGGEST
    name           TEXT    NOT NULL,
    system_prompt  TEXT    NOT NULL,
    user_prompt    TEXT    NOT NULL,
    output_schema  JSONB   NOT NULL DEFAULT '{}',
    is_active      BOOLEAN NOT NULL DEFAULT TRUE,
    updated_by     BIGINT  REFERENCES users(id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- 4. 发展档案
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS archives (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_user_id  BIGINT   NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    student_no       TEXT     NOT NULL UNIQUE,
    real_name        TEXT     NOT NULL,
    gender           TEXT     CHECK (gender IN ('男', '女')),
    ethnicity        TEXT,
    birth_date       DATE,
    native_place     TEXT,
    id_card_enc      TEXT,                      -- Fernet 加密
    id_card_masked   TEXT,                      -- 420***********1234
    major            TEXT,
    class_name       TEXT,
    college_id       BIGINT   NOT NULL REFERENCES orgs(id) ON DELETE RESTRICT,
    branch_id        BIGINT   NOT NULL REFERENCES orgs(id) ON DELETE RESTRICT,
    batch_id         BIGINT   REFERENCES batches(id) ON DELETE SET NULL,
    current_stage    SMALLINT NOT NULL DEFAULT 1 REFERENCES stages(code),
    status           TEXT     NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'COMPLETED', 'SUSPENDED')),
    profile_extra    JSONB    NOT NULL DEFAULT '{}',   -- 培养联系人、入党介绍人等
    anon_code        TEXT     NOT NULL UNIQUE,         -- 去隐私导出用匿名编号
    data_source      TEXT     NOT NULL DEFAULT 'MANUAL' CHECK (data_source IN ('DEMO', 'IMPORT', 'MANUAL')),
    is_demo          BOOLEAN  NOT NULL DEFAULT FALSE,
    timeline_updated_at TIMESTAMPTZ,                   -- 时间节点最近变化时间，用于判断报告是否过期
    created_by       BIGINT   REFERENCES users(id) ON DELETE SET NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_archives_branch ON archives(branch_id, current_stage);
CREATE INDEX IF NOT EXISTS ix_archives_college ON archives(college_id);
CREATE INDEX IF NOT EXISTS ix_archives_batch ON archives(batch_id);

-- ---------------------------------------------------------------------
-- 5. 提交包（审核流转的基本单位，一个档案每个阶段一个）
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS submissions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    archive_id        BIGINT   NOT NULL REFERENCES archives(id) ON DELETE CASCADE,
    stage_code        SMALLINT NOT NULL REFERENCES stages(code),
    batch_id          BIGINT   REFERENCES batches(id) ON DELETE SET NULL,
    college_id        BIGINT   NOT NULL REFERENCES orgs(id) ON DELETE RESTRICT,
    branch_id         BIGINT   NOT NULL REFERENCES orgs(id) ON DELETE RESTRICT,
    status            TEXT     NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'BRANCH_REVIEW', 'CROSS_REVIEW',
                                 'COLLEGE_REVIEW', 'ORG_FILING', 'FILED', 'RETURNED')),
    return_level      TEXT     CHECK (return_level IN ('BRANCH', 'CROSS', 'COLLEGE', 'ORG')),
    round_no          INTEGER  NOT NULL DEFAULT 1 CHECK (round_no >= 1),   -- 每次退回后重新提交 +1
    latest_report_id  BIGINT,                      -- 外键见第 12 节（循环引用）
    ai_status         TEXT     NOT NULL DEFAULT 'NONE' CHECK (ai_status IN ('NONE', 'QUEUED', 'RUNNING', 'DONE', 'FAILED')),
    ai_job_id         BIGINT,                      -- 外键见第 12 节
    submitted_at      TIMESTAMPTZ,
    level_entered_at  TIMESTAMPTZ,                 -- 进入当前层级的时间（审核时长、剩余天数）
    filed_at          TIMESTAMPTZ,
    filed_by          BIGINT   REFERENCES users(id) ON DELETE SET NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_submissions_stage UNIQUE (archive_id, stage_code),
    CONSTRAINT ck_submissions_return CHECK ((status = 'RETURNED') = (return_level IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS ix_submissions_status ON submissions(status, branch_id);
CREATE INDEX IF NOT EXISTS ix_submissions_batch ON submissions(batch_id, status);
CREATE INDEX IF NOT EXISTS ix_submissions_college ON submissions(college_id, status);

-- ---------------------------------------------------------------------
-- 6. 材料、版本、解析结果
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS materials (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    archive_id         BIGINT   NOT NULL REFERENCES archives(id) ON DELETE CASCADE,
    submission_id      BIGINT   NOT NULL REFERENCES submissions(id) ON DELETE CASCADE,
    stage_code         SMALLINT NOT NULL REFERENCES stages(code),
    title              TEXT     NOT NULL,                  -- 显示名，默认取原文件名
    declared_type_id   BIGINT   REFERENCES material_types(id) ON DELETE SET NULL,   -- 上传时选择的类型
    type_id            BIGINT   REFERENCES material_types(id) ON DELETE SET NULL,   -- 生效类型
    type_source        TEXT     CHECK (type_source IN ('DECLARED', 'AI', 'MANUAL')),
    type_confidence    REAL     CHECK (type_confidence IS NULL OR (type_confidence >= 0 AND type_confidence <= 1)),
    type_status        TEXT     NOT NULL DEFAULT 'PENDING' CHECK (type_status IN ('PENDING', 'AUTO', 'NEEDS_CONFIRM', 'CONFIRMED')),
    current_version_id BIGINT,                             -- 外键见第 12 节（循环引用）
    version_count      INTEGER  NOT NULL DEFAULT 0,
    status             TEXT     NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DELETED')),
    deleted_at         TIMESTAMPTZ,
    deleted_by         BIGINT   REFERENCES users(id) ON DELETE SET NULL,
    uploaded_by        BIGINT   REFERENCES users(id) ON DELETE SET NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_materials_submission ON materials(submission_id, status);
CREATE INDEX IF NOT EXISTS ix_materials_archive ON materials(archive_id, stage_code);

CREATE TABLE IF NOT EXISTS material_versions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id        BIGINT  NOT NULL REFERENCES materials(id) ON DELETE CASCADE,
    version_no         INTEGER NOT NULL CHECK (version_no >= 1),
    original_filename  TEXT    NOT NULL,
    stored_path        TEXT    NOT NULL UNIQUE,     -- storage 下相对路径，文件名为随机 UUID
    file_ext           TEXT    NOT NULL CHECK (file_ext IN ('pdf', 'jpg', 'jpeg', 'png', 'docx')),
    mime_type          TEXT    NOT NULL,
    file_size          BIGINT  NOT NULL CHECK (file_size > 0),
    sha256             TEXT    NOT NULL,
    page_count         INTEGER,
    change_note        TEXT,
    parse_status       TEXT    NOT NULL DEFAULT 'PENDING' CHECK (parse_status IN ('PENDING', 'RUNNING', 'DONE', 'FAILED')),
    parse_error        TEXT,
    parsed_at          TIMESTAMPTZ,
    is_frozen          BOOLEAN NOT NULL DEFAULT FALSE,   -- 随提交包提交后冻结，不可再改解析结果
    uploaded_by        BIGINT  REFERENCES users(id) ON DELETE SET NULL,
    uploaded_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_material_versions UNIQUE (material_id, version_no)
);
CREATE INDEX IF NOT EXISTS ix_material_versions_sha ON material_versions(sha256);

CREATE TABLE IF NOT EXISTS parse_results (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id          BIGINT  NOT NULL UNIQUE REFERENCES material_versions(id) ON DELETE CASCADE,
    parser              TEXT    NOT NULL CHECK (parser IN ('PDF_TEXT', 'DOCX', 'OCR', 'MIXED', 'NONE')),
    ocr_engine          TEXT,
    preview_pdf_path    TEXT,                        -- 归一化预览 PDF（图片 / DOCX 转换生成）
    full_text           TEXT    NOT NULL DEFAULT '',
    char_count          INTEGER NOT NULL DEFAULT 0,
    pages               JSONB   NOT NULL DEFAULT '[]',   -- 每页文本、文字块与坐标、清晰度
