ALTER TABLE ai_reports ADD COLUMN IF NOT EXISTS handover_status TEXT
    CHECK (handover_status IS NULL OR handover_status IN ('NOT_REQUIRED', 'REQUIRED', 'DONE'));
ALTER TABLE ai_reports ADD COLUMN IF NOT EXISTS effective_recommendation TEXT
    CHECK (effective_recommendation IS NULL OR effective_recommendation IN ('SUGGEST_PASS', 'SUGGEST_RETURN', 'NEEDS_REVIEW'));
ALTER TABLE ai_reports ADD COLUMN IF NOT EXISTS handover_reasons JSONB NOT NULL DEFAULT '[]'::jsonb;

CREATE TABLE IF NOT EXISTS handover_records (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id                BIGINT NOT NULL REFERENCES ai_reports(id) ON DELETE CASCADE,
    submission_id            BIGINT NOT NULL REFERENCES submissions(id) ON DELETE CASCADE,
    assignee_id              BIGINT REFERENCES users(id) ON DELETE SET NULL,
    assignee_name            TEXT NOT NULL,
    assignee_role            TEXT NOT NULL,
    reason_codes             JSONB NOT NULL DEFAULT '[]'::jsonb,
    handover_reason          TEXT,
    ai_recommendation        TEXT,
    human_decision           TEXT NOT NULL CHECK (human_decision IN ('CONFIRM', 'OVERRIDE_PASS', 'OVERRIDE_RETURN')),
    effective_recommendation TEXT NOT NULL,
    issue_ids                JSONB NOT NULL DEFAULT '[]'::jsonb,
    material_ids             JSONB NOT NULL DEFAULT '[]'::jsonb,
    confidence_snapshot      JSONB NOT NULL DEFAULT '{}'::jsonb,
    decided_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    ip                       TEXT
);
CREATE INDEX IF NOT EXISTS ix_handover_records_report ON handover_records(report_id, decided_at DESC);
